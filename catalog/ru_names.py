PHRASES: tuple[tuple[str, str], ...] = tuple(
    sorted(_PAIRS, key=lambda item: len(item[0]), reverse=True)
)

_LEFTOVER = re.compile(r"[іїєґІЇЄҐ]|['’ʼ]")


def has_ukrainian_leftover(text: str) -> bool:
    return bool(_LEFTOVER.search(text or ""))


def _apply_case(src: str, dst: str) -> str:
    if not dst:
        return dst
    if src.isupper():
        return dst.upper()
    if src[:1].isupper():
        return dst[:1].upper() + dst[1:]
    return dst


def translate_name(text: str) -> str:
    raw = text or ""
    if not raw:
        return ""
    parts: list[str] = []
    index = 0
    length = len(raw)
    while index < length:
        matched = False
        for src, dst in PHRASES:
            end = index + len(src)
            if end > length:
                continue
            chunk = raw[index:end]
            if chunk.casefold() != src.casefold():
                continue
            prev = raw[index - 1] if index else ""
            nxt = raw[end] if end < length else ""
            if prev.isalpha() or nxt.isalpha():
                continue
            parts.append(_apply_case(chunk, dst))
            index = end
            matched = True
            break
        if not matched:
            parts.append(raw[index])
            index += 1
    return "".join(parts)
