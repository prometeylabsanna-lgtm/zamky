def chunked(items, size):
    for i in range(0, len(items), size):
        yield i // size + 1, items[i : i + size]


def dump_chunk(idx, items):
    lines = ['RU_MAP = {']
    for ua, ru in items:
        lines.append(f'    {ua!r}: {ru!r},')
    lines.append('}')
    path = OUT / f'ru_map_{idx}.py'
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return path


def main():
    all_pairs = []
    seen = set()
    for ua, ru in PAIRS + MENU + EXTRA:
        if ua in seen:
            continue
        seen.add(ua)
        all_pairs.append((ua, ru))

    paths = []
    for idx, chunk in chunked(all_pairs, 180):
        paths.append(dump_chunk(idx, chunk))

    init = OUT / '__init__.py'
    imports = '\n'.join(f'from .ru_map_{i} import RU_MAP as _M{i}' for i in range(1, len(paths) + 1))
    merge = 'RU_MAP = {}\n' + '\n'.join(f'RU_MAP.update(_M{i})' for i in range(1, len(paths) + 1))
    init.write_text(imports + '\n\n' + merge + '\n', encoding='utf-8')
    print(f'Wrote {len(all_pairs)} strings in {len(paths)} files')


if __name__ == '__main__':
    main()
