def _article_html(
    sections: tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...],
) -> str:
    parts: list[str] = []
    for title, paras, items in sections:
        parts.append(f"<h2>{escape(title)}</h2>")
        for para in paras:
            parts.append(f"<p>{escape(para)}</p>")
        if items:
            lis = "".join(f"<li>{escape(item)}</li>" for item in items)
            parts.append(f"<ul>{lis}</ul>")
    return "\n".join(parts)


